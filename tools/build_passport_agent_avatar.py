#!/usr/bin/env python3
"""Pack a generated four-by-two transparent Nora sheet into native LCD frames."""
from __future__ import annotations
import argparse
import hashlib
import json
from pathlib import Path
from PIL import Image
from build_passport_assets import validate_destination

WIDTH,HEIGHT=128,132

def generate(sheet: Path,output: Path):
    validate_destination(output,True)
    with Image.open(sheet) as source:
        if source.mode!='RGBA' or source.width%4 or source.height%2:
            raise ValueError('Expected a transparent RGBA sheet with four columns and two rows')
        if min(source.width//4,source.height//2)<64 or source.getchannel('A').getextrema()[0]!=0:
            raise ValueError('Expected transparent margins and cells of at least 64 pixels')
        cells=[]
        for index in range(8):
            x=index%4*source.width//4;y=index//4*source.height//2
            cell=source.crop((x,y,x+source.width//4,y+source.height//2))
            bounds=cell.getchannel('A').point(lambda a:255 if a>=32 else 0).getbbox()
            if not bounds:raise ValueError('Empty character cell')
            # Align the sprite baseline/scale across poses, retaining actual alpha.
            bounds=(max(0,bounds[0]-2),max(0,bounds[1]-2),min(cell.width,bounds[2]+2),min(cell.height,bounds[3]+2))
            cells.append(cell.crop(bounds))
    scale=min((WIDTH-4)/max(c.width for c in cells),(HEIGHT-2)/max(c.height for c in cells))
    lines=['/* Private Nora art; generated by build_passport_agent_avatar.py. */','#include "passport_assets.h"']
    for index,cell in enumerate(cells):
        resized=cell.resize((max(1,round(cell.width*scale)),max(1,round(cell.height*scale))),Image.Resampling.LANCZOS)
        frame=Image.new('RGBA',(WIDTH,HEIGHT));frame.paste(resized,((WIDTH-resized.width)//2,HEIGHT-resized.height))
        payload=bytearray()
        for r,g,b in frame.convert('RGB').getdata():
            value=((r>>3)<<11)|((g>>2)<<5)|(b>>3);payload.extend((value&255,value>>8))
        payload.extend(frame.getchannel('A').tobytes())
        lines.append(f'static const uint8_t nora_{index}[] = {{')
        lines.extend('    '+','.join(f'0x{b:02x}' for b in payload[start:start+24])+',' for start in range(0,len(payload),24))
        lines.append('};')
    lines.append('static const lv_image_dsc_t nora_frames[8] = {')
    for index in range(8):
        lines.append('    {.header={.magic=LV_IMAGE_HEADER_MAGIC,.cf=LV_COLOR_FORMAT_RGB565A8,'+
                     f'.w={WIDTH},.h={HEIGHT},.stride={WIDTH*2}'+'},'+
                     f'.data_size={WIDTH*HEIGHT*3},.data=nora_{index}'+'},')
    lines+=['};','const char passport_agent_name[] = "Nora";',
            'const lv_image_dsc_t *passport_agent_avatar_frame(unsigned frame) {return &nora_frames[frame<8?frame:0];}']
    source='\n'.join(lines)+'\n'
    manifest={'schema':1,'private':True,'name':'Nora','width':WIDTH,'height':HEIGHT,'frame_count':8,
              'pixel_bytes':8*WIDTH*HEIGHT*3,'format':'RGB565A8',
              'sheet_sha256':hashlib.sha256(sheet.read_bytes()).hexdigest(),'source_sha256':hashlib.sha256(source.encode()).hexdigest()}
    (output/'images').mkdir(parents=True,exist_ok=True);(output/'passport').mkdir(parents=True,exist_ok=True)
    (output/'images/passport_agent_avatar.c').write_text(source,encoding='utf-8',newline='\n')
    (output/'passport/agent-avatar-manifest.json').write_text(json.dumps(manifest,sort_keys=True,indent=2)+'\n',encoding='utf-8',newline='\n')
    return manifest

def main():
    p=argparse.ArgumentParser(description=__doc__);p.add_argument('--sheet',type=Path,required=True);p.add_argument('--output',type=Path,required=True)
    args=p.parse_args();m=generate(args.sheet,args.output)
    print(f'Nora: {m["frame_count"]} native frames, {m["pixel_bytes"]} Flash pixel bytes')

if __name__=='__main__':main()
